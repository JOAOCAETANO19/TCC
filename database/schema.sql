-- ============================================================
-- FOTO DE PERFIL (AVATAR) NO STORAGE (incremental)
-- ------------------------------------------------------------
-- Em instalações EXISTENTES execute este bloco no SQL Editor;
-- em instalações novas (script inteiro) a coluna avatar_url já
-- está no CREATE TABLE acima e todo o restante é idempotente. Há
-- uma versão destacada em database/migracao-portfolio-avatar.sql.
--
-- Convenção de caminho dos arquivos:
--   avatars/<id do usuário>/avatar.jpg  (ou avatar.png)
-- O primeiro segmento do caminho identifica o dono — é isso que
-- as políticas usam para autorizar.
--
-- Privacidade: a foto segue EXATAMENTE a regra do portfólio
-- público. O bucket "avatars" é PRIVADO (public = false), ou
-- seja, nenhuma imagem é servida por URL pública: toda exibição
-- passa por URL assinada, e criar essa URL exige permissão de
-- leitura no storage.objects. A política de leitura consulta
-- profiles.portfolio_public — visitante anônimo (papel anon) só
-- vê a foto de quem publicou o portfólio. Perfil privado = foto
-- inacessível para anônimos, mesmo com o caminho exato do
-- arquivo em mãos.
-- ============================================================

alter table public.profiles add column if not exists avatar_url text;

-- O papel anon também precisa ler avatar_url nos perfis públicos
-- (grant por coluna, sem abrir email/age/is_admin).
grant select (avatar_url) on public.profiles to anon;

-- Bucket privado (public = false). Os limites de 2 MB e de
-- allowed_mimetypes (JPG/PNG) são aplicados SOMENTE quando as
-- colunas correspondentes existirem em storage.buckets — nem
-- todas as versões do Supabase Storage as possuem. A privacidade
-- de fato vem das policies (RLS), não dessas colunas.
-- O frontend valida tipo e tamanho antes do upload como primeira
-- linha de defesa.
do $$
begin
  insert into storage.buckets (id, name, public)
  values ('avatars', 'avatars', false)
  on conflict (id) do update set public = false;

  if exists (select 1 from information_schema.columns
             where table_schema = 'storage' and table_name = 'buckets'
               and column_name = 'file_size_limit') then
    update storage.buckets set file_size_limit = 2097152 where id = 'avatars';
  end if;

  if exists (select 1 from information_schema.columns
             where table_schema = 'storage' and table_name = 'buckets'
               and column_name = 'allowed_mimetypes') then
    update storage.buckets set allowed_mimetypes = '{image/jpeg,image/png}' where id = 'avatars';
  end if;
end $$;

-- O dono faz upload da própria foto (pasta com o seu id).
drop policy if exists avatars_owner_insert on storage.objects;
create policy avatars_owner_insert on storage.objects
  for insert to authenticated
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

-- O dono substitui a própria foto.
drop policy if exists avatars_owner_update on storage.objects;
create policy avatars_owner_update on storage.objects
  for update to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

-- O dono remove a própria foto.
drop policy if exists avatars_owner_delete on storage.objects;
create policy avatars_owner_delete on storage.objects
  for delete to authenticated
  using (bucket_id = 'avatars' and (storage.foldername(name))[1] = auth.uid()::text);

-- Leitura autenticada: a própria foto, sempre; fotos de outros
-- perfis somente se o portfólio deles estiver público.
drop policy if exists avatars_owner_read on storage.objects;
create policy avatars_owner_read on storage.objects
  for select to authenticated
  using (
    bucket_id = 'avatars'
    and (
      (storage.foldername(name))[1] = auth.uid()::text
      or (storage.foldername(name))[1] in (select id::text from public.profiles where portfolio_public = true and not coalesce(is_blocked, false))
    )
  );

-- Leitura anônima: apenas fotos de quem publicou o portfólio (e não está
-- bloqueado — bloqueados somem do portfólio público, foto incluída).
drop policy if exists avatars_public_read on storage.objects;
create policy avatars_public_read on storage.objects
  for select to anon
  using (
    bucket_id = 'avatars'
    and (storage.foldername(name))[1] in (select id::text from public.profiles where portfolio_public = true and not coalesce(is_blocked, false))
  );

-- ============================================================
-- CORREÇÃO DO XP NO SERVIDOR (incremental)
-- ------------------------------------------------------------
-- Registrado em 2026-08-20. Sintoma: o aluno concluía quiz,
-- matéria, exercício ou projeto e o XP continuava em 0 — sem
-- nenhuma mensagem de erro na tela.
--
-- Causa: as funções award_* rodavam como SECURITY INVOKER, ou
-- seja, com o papel do próprio aluno. O trigger
-- trg_protect_profile_fields (que existe para impedir que o
-- cliente edite XP à mão) então executava new.xp := old.xp e
-- descartava a premiação. O UPDATE era bem-sucedido, mas não
-- alterava nada — falha silenciosa. Além disso, o INSERT de
-- award_exercise_xp era barrado pelo RLS de certificates, que
-- só tinha política de SELECT.
--
-- Correção (já refletida nos blocos acima deste arquivo):
--   1. protect_profile_fields libera current_user = 'postgres',
--      que é como as funções SECURITY DEFINER se identificam;
--   2. as 4 funções award_* viraram SECURITY DEFINER com
--      search_path fixo em public (evita sequestro de search_path);
--   3. A emissão direta foi substituída pela avaliação no servidor;
--      INSERT em certificates não é concedido ao cliente.
--
-- As funções admin_* seguem SECURITY INVOKER de propósito: elas
-- se autorizam por current_is_admin() e o trigger já abre exceção
-- para administradores.
--
-- Em instalações NOVAS não há nada a fazer: rodar este arquivo
-- inteiro já aplica tudo. Em instalações EXISTENTES, reexecute o
-- script completo (todos os comandos são idempotentes) ou apenas
-- os blocos citados acima.
--
-- Garantias preservadas (verificadas em PostgreSQL real):
--   - o papel anon não consegue chamar as funções de XP;
--   - um aluno não concede XP nem emite certificado para outro;
--   - UPDATE direto em profiles.xp continua sem efeito;
--   - repetir exercício/projeto não duplica XP.
-- ============================================================

-- ============================================================
-- BLOQUEIO ADMINISTRATIVO DE USUÁRIOS (incremental)
-- ------------------------------------------------------------
-- Em instalações EXISTENTES execute database/migracao-bloqueio-usuarios.sql
-- no SQL Editor; em instalações novas este bloco já vem aplicado (a coluna
-- is_blocked está no CREATE TABLE acima e as funções/políticas já existem).
--
-- Regra de negócio:
--   - admin_set_blocked(target_id, blocked) bloqueia/desbloqueia um aluno;
--     só um admin ativo chama, e nunca é permitido bloquear a própria conta
--     (validado dentro da função, não só na interface).
--   - um usuário bloqueado:
--       • não entra: o cliente detecta is_blocked logo após o login e recusa
--         a sessão (o banco é a fonte da verdade da flag);
--       • não executa ações de XP: ensure_not_blocked() barra as 4 funções
--         award_* dentro do banco;
--       • não acessa dados protegidos: as políticas de leitura/escrita e
--         current_is_admin() tratam bloqueados como deslogados;
--       • não aparece em portfólios públicos: as políticas anon e as do
--         Storage exigem is_blocked = false.
-- ============================================================

alter table public.profiles add column if not exists is_blocked boolean not null default false;


-- CENTRO DE ESTUDOS: versão atual (mesmo conteúdo da migração incremental).
-- Pratica.dev: trilhas, atividades, avaliação e emissão de certificados.
-- Execute DEPOIS das migrações anteriores e ANTES de publicar o novo frontend.
-- Idempotente. Preserva certificados e XP já existentes.
-- A conclusão de aulas é uma declaração do aluno, não medição do player.

create table if not exists public.course_catalog (
  subject_id text primary key,
  certificate_title text not null,
  lesson_count integer not null check (lesson_count > 0),
  pass_percent integer not null check (pass_percent between 1 and 100)
);

create table if not exists public.course_questions (
  subject_id text not null references public.course_catalog(subject_id),
  question_number integer not null check (question_number > 0),
  prompt text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) >= 2),
  correct_index integer not null check (correct_index >= 0 and correct_index < jsonb_array_length(options)),
  explanation text not null,
  primary key (subject_id, question_number)
);

create table if not exists public.course_lesson_progress (
  user_id uuid not null references public.profiles(id) on delete cascade,
  subject_id text not null references public.course_catalog(subject_id),
  lesson_index integer not null check (lesson_index > 0),
  completed_at timestamptz not null default now(),
  primary key (user_id, subject_id, lesson_index)
);

create table if not exists public.course_exercises (
  user_id uuid not null references public.profiles(id) on delete cascade,
  subject_id text not null references public.course_catalog(subject_id),
  answer text not null check (char_length(btrim(answer)) between 30 and 4000),
  submitted_at timestamptz not null default now(),
  primary key (user_id, subject_id)
);

create table if not exists public.course_assessment_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  subject_id text not null references public.course_catalog(subject_id),
  correct_count integer not null check (correct_count >= 0),
  question_count integer not null check (question_count > 0 and correct_count <= question_count),
  passed boolean not null,
  feedback jsonb not null,
  attempted_at timestamptz not null default now()
);
create index if not exists course_attempts_user_subject_idx
  on public.course_assessment_attempts(user_id, subject_id, attempted_at desc);

