    async function passLab(id) {
      w.openProjectLab(id);
      const code = el('lab-code-js'); code.value = solutions[id]; code.dispatchEvent(new w.Event('input', { bubbles: true }));
      w.testProjectLab();
      do {
        const frame = el('project-lab-test-slot').querySelector('iframe');
        const { message, errors } = await executeFrame(frame.srcdoc);
        assert.deepEqual(errors, []); assert.equal(message.type, 'results'); assert.ok(message.results.every(item => item.passed));
        w.dispatchEvent(new w.MessageEvent('message', { source: frame.contentWindow, data: message }));
      } while (el('project-lab-test-slot').querySelector('iframe'));
      assert.equal(el('project-lab-complete').disabled, false);
    }
    await tick(); await login(); w.switchTab('projetos');
    check(await xp() === 350 && el('projects-grid').textContent.includes('Projeto já concluído') && el('projects-grid').textContent.includes('Praticar novamente'), 'login recupera projetos e 350 XP já conquistados');
