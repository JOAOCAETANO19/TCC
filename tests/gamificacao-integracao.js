// Jornada com as funções reais de supabase.js ligadas às RPCs em PGlite.
// Auth e transporte são simulados; não faz chamadas ao projeto publicado.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const { PGlite } = require('@electric-sql/pglite');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const ana = '11111111-1111-4111-8111-111111111111';
const bia = '22222222-2222-4222-8222-222222222222';
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; console.log(`✓ ${message}`); }

(async () => {
  const pg = new PGlite(); let dom;
  try {
    await pg.exec(`
      create role anon; create role authenticated; create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mimetypes text[]);
      create table storage.objects(id bigint generated by default as identity, bucket_id text, name text);
      create function storage.foldername(path text) returns text[] language sql immutable as $$ select string_to_array(path, '/') $$;
      grant usage on schema auth, storage, public to anon, authenticated;
    `);
    await pg.exec(read('database/schema.sql').replace('create extension if not exists pgcrypto;', ''));
    await pg.exec(`
      insert into auth.users(id,email,raw_user_meta_data) values
        ('${ana}','ana@exemplo.com','{"name":"Ana","age":18}'),
        ('${bia}','bia@exemplo.com','{"name":"Bia","age":18}');
      update public.profiles set xp=50,level=1,quiz_done=true,track='Front-end' where id='${ana}';
      update public.profiles set xp=300,level=4,quiz_done=true where id='${bia}';
      insert into public.quiz_answers(user_id,question,answer) values ('${ana}',1,'Histórico');
      insert into public.course_lesson_progress(user_id,subject_id,lesson_index) values ('${ana}','html',1);
      insert into public.user_projects(user_id,project_id) values ('${ana}',1);
      insert into public.certificates(user_id,subject_id,title) values ('${ana}','html','HTML antigo');
      select set_config('request.jwt.claim.sub','${bia}',false); set role authenticated;
      select public.set_ranking_participation(true,'Bia_Dev');
      reset role; select set_config('request.jwt.claim.sub','',false);
    `);
    const rows = async (sql, params = []) => (await pg.query(sql, params)).rows;
    const as = async id => pg.exec(`reset role; select set_config('request.jwt.claim.sub','${id || ''}',false); set role ${id ? 'authenticated' : 'anon'};`);
    const rpcMap = {
      get_my_gamification_settings: () => ['select public.get_my_gamification_settings() as value', [], true],
      save_profile_appearance: a => ['select public.save_profile_appearance($1,$2) as value', [a.p_theme, a.p_frame], true],
      get_public_profile_appearance: a => ['select public.get_public_profile_appearance($1) as value', [a.p_user_id], true],
      get_my_challenge_progress: () => ['select public.get_my_challenge_progress() as value', [], true],
      set_ranking_participation: a => ['select public.set_ranking_participation($1,$2) as value', [a.p_join, a.p_alias], true],
      get_optional_ranking: () => ['select * from public.get_optional_ranking()', [], false],
      award_project_xp: a => ['select public.award_project_xp($1) as value', [a.p_project_id], true]
    };
    const calls = [];
    const fakeClient = {
      auth: {
        getSession: async () => ({ data: { session: null }, error: null }),
        signInWithPassword: async () => { await as(ana); return { data: { user: { id: ana } }, error: null }; },
        signOut: async () => { await as(null); return { error: null }; },
        onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } })
      },
      rpc: async (name, args = {}) => {
        calls.push({ name, args });
        try {
          if (!rpcMap[name]) throw new Error('RPC não mapeada: ' + name);
          const [sql, params, scalar] = rpcMap[name](args);
          const result = await rows(sql, params);
          return { data: scalar ? result[0].value : result, error: null };
        } catch (e) { return { data: null, error: { message: e.message } }; }
      }
    };
    dom = new JSDOM(read('index.html'), { url: 'https://joaocaetano19.github.io/TCC/', runScripts: 'outside-only', pretendToBeVisual: true });
    const w = dom.window; const el = id => w.document.getElementById(id);
    w.console.warn = () => {}; w.lucide = { createIcons() {} }; w.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
    w.supabase = { createClient: () => fakeClient };
    w.eval(read('supabase.js'));
    // Estas leituras não fazem parte do recurso testado; continuam usando
    // tabelas e RLS reais, sem implementar toda a API fluent do SDK.
    Object.assign(w, {
      fetchProfile: async id => (await rows('select * from public.profiles where id=$1', [id]))[0],
      fetchUserProjects: async id => rows('select project_id from public.user_projects where user_id=$1', [id]),
      fetchCertificates: async id => rows('select * from public.certificates where user_id=$1', [id]),
      fetchQuizAnswers: async id => rows('select question,answer from public.quiz_answers where user_id=$1 order by question', [id]),
      fetchCourseProgress: async id => ({ lessons: await rows('select * from public.course_lesson_progress where user_id=$1', [id]), exercises: [], attempts: [] }),
      fetchAvatarSignedUrl: async () => null,
      fetchPublicProfile: async () => null, fetchPublicProjects: async () => [], fetchPublicCertificates: async () => []
    });
    w.eval(read('gamification.js') + '\n' + read('course-content.js') + '\n' + read('script.js'));
    const login = async () => { el('login-email').value = 'ana@exemplo.com'; el('login-password').value = '123456'; await w.handleLogin(); await tick(); await tick(); };
    await tick(); await login(); w.switchTab('desafios'); await tick(); await tick();
    check(el('challenge-content').textContent.includes('3 de 6 metas concluídas') && el('ranking-content').textContent.includes('NÃO ESTÁ PARTICIPANDO'), 'frontend e RPC real recuperam metas históricas com ranking desativado');
    check(!calls.some(call => call.name === 'get_optional_ranking'), 'antes da adesão o cliente não solicita o placar');
    w.switchTab('perfil');
    check(el('appearance-theme-oceano').disabled && el('appearance-frame-menta').disabled, '50 XP mantêm opções bloqueadas na interface');
    w.switchTab('projetos');
    const button = w.document.createElement('button');
    await w.startProject(7, 'E-commerce', button);
    check((await rows('select xp,level from public.profiles where id=$1', [ana]))[0].xp === 250 && button.textContent.includes('Concluído'), 'projeto manual existente concede XP pelas regras originais');
    w.switchTab('perfil');
    await w.Gamification.chooseAppearance('theme', 'aurora');
    await w.Gamification.chooseAppearance('frame', 'menta');
    check(el('profile-shell').dataset.profileTheme === 'aurora' && el('prof-avatar').classList.contains('avatar-frame-menta'), 'desbloqueios alcançados são gravados por supabase.js e aplicados na tela');
    check((await rows('select xp,level from public.profiles where id=$1', [ana]))[0].xp === 250, 'trocar estilo não desconta XP no banco real');
    w.switchTab('desafios'); await tick(); await tick();
    check(el('challenge-content').querySelector('[data-challenge="projeto-3"] progress').value === 2, 'nova consulta reflete projeto concluído sem criar progresso paralelo');
    el('ranking-alias').value = 'Lua_Dev'; await w.Gamification.submitRanking(); await tick(); await tick();
    check(el('ranking-content').textContent.includes('Bia_Dev') && el('ranking-content').textContent.includes('Lua_Dev') && el('ranking-content').querySelector('.ranking-row.is-self'), 'adesão real retorna somente o placar de participantes e marca a própria linha');
    check(calls.some(call => call.name === 'set_ranking_participation' && call.args.p_join === true && call.args.p_alias === 'Lua_Dev'), 'cliente envia decisão e apelido nas chaves esperadas pela RPC');
    await w.handleLogout(); await login(); w.switchTab('perfil');
    check(el('profile-shell').dataset.profileTheme === 'aurora' && el('prof-avatar').classList.contains('avatar-frame-menta'), 'novo login recupera aparência armazenada no banco');
    w.switchTab('desafios'); await tick(); await tick();
    check(el('ranking-content').textContent.includes('VOCÊ ESTÁ PARTICIPANDO') && el('ranking-alias').value === 'Lua_Dev', 'participação e apelido sobrevivem ao novo login');
    await w.Gamification.leaveRanking();
    check(el('ranking-content').textContent.includes('Você saiu') && !(await w.fetchGamificationSettings()).ranking_joined, 'saída real remove adesão sem afetar acesso às metas');
    await as(bia);
    const ranking = await rows('select * from public.get_optional_ranking()');
    check(!ranking.some(row => row.alias === 'Lua_Dev') && ranking.some(row => row.alias === 'Bia_Dev'), 'outra participante deixa de ver quem saiu em nova consulta');
    await as(ana);
    const legacy = await rows(`select xp,level,quiz_done,track,
      (select count(*) from public.quiz_answers where user_id=$1) as quiz,
      (select count(*) from public.certificates where user_id=$1) as certs,
      (select count(*) from public.user_projects where user_id=$1) as projects
      from public.profiles where id=$1`, [ana]);
    check(legacy[0].xp === 250 && legacy[0].level === 3 && legacy[0].quiz_done && legacy[0].track === 'Front-end' && Number(legacy[0].quiz) === 1 && Number(legacy[0].certs) === 1 && Number(legacy[0].projects) === 2, 'quiz, certificado, projetos e nível permanecem preservados durante toda a jornada');
    console.log(`\n${checks} verificações de integração da gamificação passaram.`);
  } finally { if (dom) dom.window.close(); await pg.close(); }
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
