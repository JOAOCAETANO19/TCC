// Jornada do navegador até as RPCs de PostgreSQL reais (PGlite), sem rede.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
const { PGlite } = require('@electric-sql/pglite');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
const uid = '11111111-1111-4111-8111-111111111111';
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; console.log(`✓ ${message}`); }

(async () => {
  const pg = new PGlite();
  let dom;
  try {
    // Substitui apenas estruturas externas do Supabase; as tabelas, RLS,
    // triggers, grants e RPCs da aplicação são os do schema.sql completo.
    await pg.exec(`
      create role anon; create role authenticated;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mimetypes text[]);
      create table storage.objects(id bigint generated by default as identity, bucket_id text, name text);
      create function storage.foldername(path text) returns text[] language sql immutable as $$ select string_to_array(path, '/') $$;
      grant usage on schema auth, storage, public to anon, authenticated;
    `);
    // pgcrypto não vem no PGlite; o schema não depende de nenhuma função dela.
    const schema = read('database/schema.sql').replace('create extension if not exists pgcrypto;', '');
    await pg.exec(schema);
    await pg.exec(schema);
    check((await pg.query('select count(*)::int as n from public.course_questions')).rows[0].n === 72, 'schema completo é idempotente e cadastra 72 questões');
    await pg.exec(read('database/correcao-xp.sql'));
    await pg.exec(read('database/migracao-bloqueio-usuarios.sql'));
    const legacyPrivileges = (await pg.query(`select
      has_table_privilege('authenticated', 'public.certificates', 'INSERT') as can_insert,
      has_function_privilege('authenticated', 'public.award_exercise_xp(text,text)', 'EXECUTE') as can_award`)).rows[0];
    check(!legacyPrivileges.can_insert && !legacyPrivileges.can_award, 'migrações históricas reaplicadas não reabrem emissão direta');
    await pg.exec(read('database/migracao-cursos-certificados.sql'));
    const key = (await pg.query(`select correct_index from public.course_questions where subject_id='html' order by question_number`)).rows.map(r => r.correct_index);
    await pg.exec(`
      insert into auth.users(id, email, raw_user_meta_data) values ('${uid}', 'ana@exemplo.com', '{"name":"Ana","age":18}'::jsonb);
      select set_config('request.jwt.claim.sub', '${uid}', false); set role authenticated;
    `);
    async function query(sql, params = []) { return (await pg.query(sql, params)).rows; }
    async function rpc(sql, params = []) { return (await query(sql, params))[0].value; }
    dom = new JSDOM(read('index.html'), { url: 'https://joaocaetano19.github.io/TCC/', runScripts: 'outside-only', pretendToBeVisual: true });
    const w = dom.window;
    w.console.warn = () => {};
    w.lucide = { createIcons() {} };
    w.matchMedia = () => ({ matches: false, addEventListener() {}, removeEventListener() {} });
    Object.assign(w, {
      getSession: async () => null,
      supabaseLogin: async () => ({ id: uid }), supabaseLogout: async () => {},
      fetchProfile: async id => (await query('select * from public.profiles where id=$1', [id]))[0],
      fetchUserProjects: async () => [], fetchQuizAnswers: async () => [],
      fetchCertificates: async id => query('select * from public.certificates where user_id=$1 order by issued_at desc', [id]),
      fetchCourseProgress: async id => ({
        lessons: await query('select subject_id, lesson_index, completed_at from public.course_lesson_progress where user_id=$1', [id]),
        exercises: await query('select subject_id, answer, submitted_at from public.course_exercises where user_id=$1', [id]),
        attempts: await query('select subject_id, correct_count, question_count, passed, feedback, attempted_at from public.course_assessment_attempts where user_id=$1 order by attempted_at desc', [id])
      }),
      awardSubjectViewXP: async id => { await query('select public.award_subject_view_xp($1)', [id]); },
      markCourseLesson: async (id, index) => { await query('select public.mark_course_lesson_complete($1,$2)', [id, index]); },
      saveCourseExercise: async (id, answer) => { await query('select public.save_course_exercise($1,$2)', [id, answer]); },
      getCourseAssessment: async id => rpc('select public.get_course_assessment($1) as value', [id]),
      submitCourseAssessment: async (id, answers) => rpc('select public.submit_course_assessment($1,$2::jsonb) as value', [id, JSON.stringify(answers)]),
      fetchAvatarSignedUrl: async () => null,
      fetchPublicProfile: async () => null, fetchPublicProjects: async () => [], fetchPublicCertificates: async () => []
    });
    w.eval(read('course-content.js') + '\n' + read('script.js'));
    await tick();
    w.document.getElementById('login-email').value = 'ana@exemplo.com';
    w.document.getElementById('login-password').value = '123456';
    await w.handleLogin(); await tick(); await tick();
    w.switchTab('estudos'); await w.openSubject('html');
    check(w.document.getElementById('course-assessment').textContent.includes('bloqueada'), 'curso real começa com avaliação bloqueada');
    for (let i = 1; i <= 3; i++) await w.completeCourseLesson('html', i);
    const solution = 'Minha página possui cabeçalho, parágrafo, lista e um link acessível.';
    w.document.getElementById('course-exercise-answer').value = solution;
    await w.submitCourseExercise('html');
    await w.startCourseAssessment('html');
    check(w.document.querySelectorAll('.course-question').length === 6, 'frontend apresenta as seis questões recebidas da RPC');
    const choose = answers => answers.forEach((value, i) => { w.document.querySelector(`input[name="assessment-html-${i + 1}"][value="${value}"]`).checked = true; });
    choose(key.map((value, i) => i < 2 ? (value + 1) % 4 : value));
    await w.submitCourseAssessmentUI('html');
    check(w.document.getElementById('course-assessment').textContent.includes('4 de 6') && w.document.getElementById('course-assessment').textContent.includes('Qual elemento identifica a navegação') && (await query('select * from public.certificates')).length === 0, 'correção real reprova, mostra feedback com enunciado e não emite certificado');
    await w.startCourseAssessment('html');
    choose(key.map((value, i) => i === 0 ? (value + 1) % 4 : value));
    await w.submitCourseAssessmentUI('html');
    const certificates = await query('select * from public.certificates');
    check(certificates.length === 1 && certificates[0].subject_id === 'html' && w.document.getElementById('course-assessment').textContent.includes('Você foi aprovado'), '5 de 6 emite certificado real e atualiza a interface');
    check((await query('select xp from public.profiles where id=$1', [uid]))[0].xp === 40, 'trigger e RPCs reais concedem XP corretamente');
    await w.handleLogout();
    await w.handleLogin(); await tick(); await tick();
    w.switchTab('estudos'); await w.openSubject('html');
    check(w.document.getElementById('course-progress-summary').textContent.includes('3 de 3') && w.document.getElementById('course-exercise-answer').value === solution, 'novo login recupera aulas e atividade do banco');
    check(w.document.getElementById('course-assessment').textContent.includes('Última tentativa:') && w.document.getElementById('course-assessment').textContent.includes('Ver feedback') && w.document.getElementById('course-assessment').textContent.includes('Abrir certificado'), 'novo login recupera tentativa, feedback e certificado');
    await w.startCourseAssessment('html'); choose(key); await w.submitCourseAssessmentUI('html');
    check((await query('select xp from public.profiles where id=$1', [uid]))[0].xp === 40 && (await query('select * from public.certificates')).length === 1, 'refazer avaliação real não duplica XP ou certificado');
    console.log(`\n${checks} verificações de integração passaram.`);
  } finally {
    if (dom) dom.window.close();
    await pg.close();
  }
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
