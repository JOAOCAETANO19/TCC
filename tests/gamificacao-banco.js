// Exercita a migração incremental, permissões e RPCs com PostgreSQL local.
// Auth e Storage são substituídos por estruturas mínimas; não acessa produção.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const ids = {
  ana: '11111111-1111-4111-8111-111111111111',
  bia: '22222222-2222-4222-8222-222222222222',
  caio: '33333333-3333-4333-8333-333333333333',
  dani: '44444444-4444-4444-8444-444444444444',
  blocked: '55555555-5555-4555-8555-555555555555',
  missing: '66666666-6666-4666-8666-666666666666'
};
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; console.log(`✓ ${message}`); }

(async () => {
  const pg = new PGlite();
  try {
    await pg.exec(`
      create role anon; create role authenticated;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mimetypes text[]);
      create table storage.objects(id bigint generated by default as identity, bucket_id text, name text);
      create function storage.foldername(path text) returns text[] language sql immutable as $$ select string_to_array(path, '/') $$;
      grant usage on schema auth, storage, public to anon, authenticated;
    `);
    const marker = '-- ===== PERSONALIZAÇÃO, DESAFIOS E RANKING VOLUNTÁRIO =====';
    const fullSchema = read('database/schema.sql');
    assert.ok(fullSchema.includes(marker));
    const oldSchema = fullSchema.split(marker)[0].replace('create extension if not exists pgcrypto;', '');
    const migration = read('database/migracao-perfil-desafios-ranking.sql');
    check(fullSchema.endsWith(migration), 'schema completo contém a mesma migração incremental');
    await pg.exec(oldSchema);
    const rows = async (sql, params = []) => (await pg.query(sql, params)).rows;
    const value = async (sql, params = []) => (await rows(sql, params))[0].value;
    const as = async (id, role = 'authenticated') => {
      await pg.exec(`reset role; select set_config('request.jwt.claim.sub', '${id || ''}', false); set role ${role};`);
    };
    await pg.exec(`
      insert into auth.users(id,email,raw_user_meta_data) values
        ('${ids.ana}','ana@exemplo.com','{"name":"Ana","age":17}'),
        ('${ids.bia}','bia@exemplo.com','{"name":"Bia","age":18}'),
        ('${ids.caio}','caio@exemplo.com','{"name":"Caio","age":21}'),
        ('${ids.dani}','dani@exemplo.com','{"name":"Dani","age":20}'),
        ('${ids.blocked}','bloqueado@exemplo.com','{"name":"Bloqueado","age":19}');
      update public.profiles set xp=50, level=1, quiz_done=true, track='Front-end', goal='Aprender' where id='${ids.ana}';
      update public.profiles set xp=500, level=6 where id in ('${ids.bia}','${ids.caio}');
      update public.profiles set xp=800, level=9 where id='${ids.dani}';
      update public.profiles set xp=900, level=10 where id='${ids.blocked}';
      insert into public.quiz_answers(user_id,question,answer) values ('${ids.ana}',1,'Resposta antiga');
      insert into public.course_lesson_progress(user_id,subject_id,lesson_index) values ('${ids.ana}','html',1),('${ids.ana}','html',2);
      insert into public.user_projects(user_id,project_id) values ('${ids.ana}',1),('${ids.ana}',7);
      insert into public.certificates(user_id,subject_id,title) values ('${ids.ana}','html','Certificado antigo');
    `);
    const legacyBefore = JSON.stringify(await rows(`select xp,level,quiz_done,track,goal,
      (select count(*) from public.quiz_answers where user_id='${ids.ana}') as quiz,
      (select count(*) from public.course_lesson_progress where user_id='${ids.ana}') as lessons,
      (select count(*) from public.user_projects where user_id='${ids.ana}') as projects,
      (select count(*) from public.certificates where user_id='${ids.ana}') as certs
      from public.profiles where id='${ids.ana}'`));
    await pg.exec(migration);
    await pg.exec(migration);
    const legacyAfter = JSON.stringify(await rows(`select xp,level,quiz_done,track,goal,
      (select count(*) from public.quiz_answers where user_id='${ids.ana}') as quiz,
      (select count(*) from public.course_lesson_progress where user_id='${ids.ana}') as lessons,
      (select count(*) from public.user_projects where user_id='${ids.ana}') as projects,
      (select count(*) from public.certificates where user_id='${ids.ana}') as certs
      from public.profiles where id='${ids.ana}'`));
    check(legacyAfter === legacyBefore, 'aplicar e reaplicar migração preserva XP, nível, quiz, aulas, projetos e certificados');
    const source = read('gamification.js');
    const catalog = name => [...source.match(new RegExp(`const ${name} = \\[([\\s\\S]*?)\\];`))[1].matchAll(/id: '([^']+)', name: '[^']+', minXp: (\d+)/g)].map(m => [m[1], Number(m[2])]);
    for (const [kind, fn] of [['THEMES', 'profile_theme_min_xp'], ['FRAMES', 'profile_frame_min_xp']]) {
      const options = catalog(kind);
      assert.equal(options.length, 4);
      for (const [id, minimum] of options) assert.equal(await value(`select public.${fn}($1) as value`, [id]), minimum);
    }
    check(true, 'todos os limiares do catálogo da interface correspondem às funções SQL');

    await as(ids.ana);
    let settings = await value('select public.get_my_gamification_settings() as value');
    check(settings.theme === 'original' && settings.frame === 'simples' && settings.ranking_joined === false && settings.ranking_alias === null, 'perfil inicial tem aparência original e participação desativada');
    const progress = await value('select public.get_my_challenge_progress() as value');
    check(progress.lessons === 2 && progress.projects === 2 && progress.certificates === 1, 'metas contam registros existentes, inclusive projeto manual e certificado antigo');
    await assert.rejects(() => rows('select * from public.get_optional_ranking()'), /participar/i);
    check(true, 'não participante não consegue ler o ranking');
    for (const sql of [
      'select * from public.profile_appearance',
      'select * from public.ranking_participants',
      `insert into public.ranking_participants(user_id,alias) values ('${ids.ana}','Teste')`,
      `insert into public.profile_appearance(user_id,theme,frame) values ('${ids.ana}','cosmos','solar')`,
      'select public.gamification_active_xp()',
      "select public.profile_theme_min_xp('cosmos')"
    ]) await assert.rejects(() => rows(sql), /permission denied/i);
    check(true, 'tabelas e auxiliares não permitem acesso direto ao cliente autenticado');
    await assert.rejects(() => rows("select public.save_profile_appearance('oceano','simples')"), /desbloqueado/i);
    await assert.rejects(() => rows("select public.save_profile_appearance('original','menta')"), /desbloqueado/i);
    await assert.rejects(() => rows("select public.save_profile_appearance('inexistente','simples')"), /inválid/i);
    await assert.rejects(() => rows("select public.save_profile_appearance(null,'simples')"), /inválid/i);
    check(true, 'banco rejeita tema, moldura bloqueada e IDs inválidos mesmo fora da interface');
    await rows(`update public.profiles set xp=9999, level=100 where id='${ids.ana}'`);
    check((await rows(`select xp,level from public.profiles where id='${ids.ana}'`))[0].xp === 50, 'edição direta do perfil não libera cosméticos por XP forjado');

    await pg.exec(`reset role; update public.profiles set xp=100,level=2 where id='${ids.ana}'; set role authenticated;`);
    let saved = await value("select public.save_profile_appearance('oceano','menta') as value");
    check(saved.theme === 'oceano' && saved.frame === 'menta', '100 XP liberam tema Oceano e moldura Menta no limite exato');
    await assert.rejects(() => rows("select public.save_profile_appearance('aurora','menta')"), /desbloqueado/i);
    await pg.exec(`reset role; update public.profiles set xp=250,level=3 where id='${ids.ana}'; set role authenticated;`);
    await value("select public.save_profile_appearance('aurora','menta') as value");
    await assert.rejects(() => rows("select public.save_profile_appearance('aurora','violeta')"), /desbloqueado/i);
    await pg.exec(`reset role; update public.profiles set xp=300,level=4 where id='${ids.ana}'; set role authenticated;`);
    await value("select public.save_profile_appearance('aurora','violeta') as value");
    await pg.exec(`reset role; update public.profiles set xp=500,level=6 where id='${ids.ana}'; set role authenticated;`);
    await value("select public.save_profile_appearance('cosmos','violeta') as value");
    await assert.rejects(() => rows("select public.save_profile_appearance('cosmos','solar')"), /desbloqueado/i);
    await pg.exec(`reset role; update public.profiles set xp=600,level=7 where id='${ids.ana}'; set role authenticated;`);
    await value("select public.save_profile_appearance('cosmos','solar') as value");
    const unchanged = (await rows(`select xp, level from public.profiles where id='${ids.ana}'`))[0];
    check(unchanged.xp === 600 && unchanged.level === 7, 'limiares de 250, 300, 500 e 600 XP são aplicados sem descontar XP ou mudar nível');
    settings = await value('select public.get_my_gamification_settings() as value');
    check(settings.theme === 'cosmos' && settings.frame === 'solar', 'aparência fica salva e é lida pelo dono');

    await as(null, 'anon');
    await assert.rejects(() => rows('select public.get_my_gamification_settings()'), /permission denied/i);
    await assert.rejects(() => rows('select public.get_my_challenge_progress()'), /permission denied/i);
    await assert.rejects(() => rows('select * from public.get_optional_ranking()'), /permission denied/i);
    await assert.rejects(() => rows('select * from public.ranking_participants'), /permission denied/i);
    check(await value(`select public.get_public_profile_appearance('${ids.ana}') as value`) === null, 'anon não acessa ranking, progresso ou aparência de portfólio privado');
    await pg.exec(`reset role; update public.profiles set portfolio_public=true where id='${ids.ana}'; set role anon;`);
    let publicAppearance = await value(`select public.get_public_profile_appearance('${ids.ana}') as value`);
    check(publicAppearance.theme === 'cosmos' && publicAppearance.frame === 'solar' && Object.keys(publicAppearance).length === 2, 'portfólio público revela apenas o tema e a moldura');
    await pg.exec(`reset role; update public.profiles set xp=0,level=1 where id='${ids.ana}'; set role anon;`);
    publicAppearance = await value(`select public.get_public_profile_appearance('${ids.ana}') as value`);
    check(publicAppearance.theme === 'original' && publicAppearance.frame === 'simples', 'redução administrativa de XP desativa aparência acima do limite também no portfólio público');
    await pg.exec(`reset role; update public.profiles set xp=600,level=7,portfolio_public=false where id='${ids.ana}';`);
    await as(ids.ana);
    settings = await value('select public.get_my_gamification_settings() as value');
    check(settings.theme === 'cosmos' && settings.frame === 'solar', 'aparência escolhida reaparece quando o XP necessário é recuperado');

    for (const args of [[true, null], [true, 'a'], [true, 'a'.repeat(25)], [true, 'email@exemplo.com'], [true, 'linha\nquebrada'], [null, 'Teste']]) {
      await assert.rejects(() => rows('select public.set_ranking_participation($1,$2)', args));
    }
    check(true, 'adesão exige decisão explícita e apelido válido sem e-mail nem controles');
    const join = await value('select public.set_ranking_participation($1,$2) as value', [true, '  Lua_Dev  ']);
    check(join.joined === true && join.alias === 'Lua_Dev', 'adesão voluntária salva apelido normalizado');
    await value('select public.set_ranking_participation($1,$2) as value', [true, 'Lua_Dev']);
    await as(ids.bia); await value('select public.set_ranking_participation($1,$2) as value', [true, 'BiaAnon']);
    await as(ids.caio); await value('select public.set_ranking_participation($1,$2) as value', [true, 'CaioAnon']);
    await as(ids.dani); await value('select public.set_ranking_participation($1,$2) as value', [true, 'DaniAnon']);
    await as(ids.blocked); await value('select public.set_ranking_participation($1,$2) as value', [true, 'Bloqueado']);
    await pg.exec(`reset role; update public.profiles set is_blocked=true,portfolio_public=true where id='${ids.blocked}';`);
    await as(ids.ana);
    let ranking = await rows('select * from public.get_optional_ranking()');
    check(ranking.length === 4 && ranking.every(row => !('user_id' in row) && !('name' in row) && !('email' in row)) && ranking.every(row => row.alias !== 'Bloqueado'), 'ranking mostra apenas participantes ativos, sem IDs ou dados do perfil');
    check(ranking[0].alias === 'DaniAnon' && ranking[0].ranking_position === 1 && ranking[1].alias === 'Lua_Dev' && ranking[1].ranking_position === 2 && ranking[1].is_self === true && ranking[2].ranking_position === 3 && ranking[3].ranking_position === 3, 'classificação ordena XP, indica a própria linha e compartilha posição em empates');
    check((await rows(`select xp,level from public.profiles where id='${ids.ana}'`))[0].xp === 600, 'participar e atualizar apelido não alteram XP');
    await value('select public.set_ranking_participation($1,$2) as value', [false, null]);
    await assert.rejects(() => rows('select * from public.get_optional_ranking()'), /participar/i);
    await as(ids.bia);
    ranking = await rows('select * from public.get_optional_ranking()');
    check(!ranking.some(row => row.alias === 'Lua_Dev'), 'sair apaga a participação e a pessoa não aparece em novas consultas');
    const biaProgress = await value('select public.get_my_challenge_progress() as value');
    check(biaProgress.lessons === 0 && biaProgress.projects === 0 && biaProgress.certificates === 0, 'progresso privado não mistura registros de outros usuários');
    await as(ids.blocked);
    for (const sql of [
      'select public.get_my_gamification_settings()', 'select public.get_my_challenge_progress()',
      "select public.save_profile_appearance('original','simples')", "select public.set_ranking_participation(true,'Teste')", 'select * from public.get_optional_ranking()'
    ]) await assert.rejects(() => rows(sql), /bloquead/i);
    await as(null, 'anon');
    check(await value(`select public.get_public_profile_appearance('${ids.blocked}') as value`) === null, 'conta bloqueada não aparece nem executa as RPCs privadas; aparência pública também é ocultada');
    await as(ids.missing);
    await assert.rejects(() => rows('select public.get_my_gamification_settings()'), /perfil indisponível/i);
    check(true, 'sessão sem perfil não consegue usar as funções privadas');

    // Insere participantes fictícios por operação administrativa local para
    // testar limite, empates e inclusão da própria pessoa fora dos 50.
    await pg.exec(`reset role;
      insert into auth.users(id,email,raw_user_meta_data)
      select md5('ficticio-' || n)::uuid, 'f' || n || '@exemplo.com', jsonb_build_object('name','Ficticio ' || n,'age',18)
      from generate_series(1,55) n;
      update public.profiles set xp=1000,level=11 where id in (select md5('ficticio-' || n)::uuid from generate_series(1,55) n);
      insert into public.ranking_participants(user_id,alias)
      select md5('ficticio-' || n)::uuid, 'Aluno_' || n from generate_series(1,55) n;
    `);
    await as(ids.bia);
    ranking = await rows('select * from public.get_optional_ranking()');
    check(ranking.length === 51 && ranking.slice(0,50).every(row => row.ranking_position === 1) && ranking[50].is_self && ranking[50].alias === 'BiaAnon', 'lista limita a 50 e inclui a própria pessoa fora do topo sem quebrar empates');
    await pg.exec(`reset role; ${migration}`);
    check((await rows(`select count(*)::int as n from public.ranking_participants where user_id='${ids.bia}'`))[0].n === 1 && (await rows(`select frame from public.profile_appearance where user_id='${ids.ana}'`))[0].frame === 'solar', 'reaplicar migração preserva adesões e preferências já salvas');
    await pg.exec(`delete from public.profiles where id='${ids.bia}';`);
    check((await rows(`select count(*)::int as n from public.ranking_participants where user_id='${ids.bia}'`))[0].n === 0, 'excluir perfil remove participação por cascata');
    console.log(`\n${checks} verificações de banco da gamificação passaram.`);
  } finally { await pg.close(); }
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
