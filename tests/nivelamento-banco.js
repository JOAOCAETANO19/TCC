// Migração do nivelamento em PostgreSQL (PGlite), com contas legadas e RLS.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { PGlite } = require('@electric-sql/pglite');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const migration = read('database/migracao-nivelamento.sql');
const schema = read('database/schema.sql');
const alice = '11111111-1111-4111-8111-111111111111';
const bob = '22222222-2222-4222-8222-222222222222';
const carol = '33333333-3333-4333-8333-333333333333';
const answers = ['Iniciante total', 'Front-end', 'Estágio em 6 meses', '3 a 5 horas', '5', '<nav>', 'A distribuição dos itens no eixo principal', '3', 'Uma versão das alterações preparadas no repositório local', 'SELECT * FROM produtos WHERE preco > 100;'];
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; console.log(`✓ ${message}`); }
async function denied(work, pattern, message) {
  let failure;
  try { await work(); } catch (e) { failure = e; }
  check(failure && pattern.test(failure.message), `${message}${failure ? '' : ' (nenhum erro)'}`);
}

(async () => {
  const pg = new PGlite();
  try {
    await pg.exec(`
      create role anon; create role authenticated;
      create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb);
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
      $$;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mimetypes text[]);
      create table storage.objects(id bigint generated by default as identity, bucket_id text, name text);
      create function storage.foldername(path text) returns text[] language sql immutable as $$ select string_to_array(path, '/') $$;
      grant usage on schema auth, storage, public to anon, authenticated;
    `);
    check(schema.includes(migration), 'schema completo incorpora a migração de nivelamento');
    // O trecho anterior à nova migração representa uma instalação já existente.
    const oldSchema = schema.slice(0, schema.lastIndexOf(migration)).replace('create extension if not exists pgcrypto;', '');
    await pg.exec(oldSchema);
    await pg.exec(`insert into auth.users(id,email,raw_user_meta_data) values
      ('${alice}','alice@example.com','{"name":"Alice","age":18}'),
      ('${bob}','bob@example.com','{"name":"Bob","age":19}'),
      ('${carol}','carol@example.com','{"name":"Carol","age":20}');`);
    async function query(sql, params = []) { return (await pg.query(sql, params)).rows; }
    async function asUser(uid) {
      await pg.exec(`reset role; select set_config('request.jwt.claim.sub', '${uid}', false); set role authenticated;`);
    }
    async function submit(values, track = values[1], goal = values[2]) {
      await query('select public.award_quiz_xp($1::jsonb,$2,$3)', [JSON.stringify(values), track, goal]);
    }
    async function xp(uid) { return (await query('select xp from public.profiles where id=$1', [uid]))[0].xp; }

    await asUser(alice);
    await submit(answers.slice(0, 3));
    check(await xp(alice) === 50 && (await query('select * from public.quiz_answers')).length === 3, 'quiz antigo registra três respostas e 50 XP');
    await pg.exec('reset role');
    await pg.exec(migration);
    await pg.exec(migration);
    const backfill = await query('select user_id from public.quiz_xp_awards order by user_id');
    check(backfill.length === 1 && backfill[0].user_id === alice, 'migração idempotente preserva a conclusão antiga sem alterar outras contas');
    check((await query('select xp from public.profiles where id=$1', [alice]))[0].xp === 50, 'migração não concede XP retroativo');
    const privileges = (await query(`select
      has_table_privilege('authenticated','public.quiz_xp_awards','select') as can_read,
      has_table_privilege('authenticated','public.quiz_xp_awards','insert') as can_insert,
      has_function_privilege('anon','public.award_quiz_xp(jsonb,text,text)','execute') as anonymous_rpc`))[0];
    check(!privileges.can_read && !privileges.can_insert && !privileges.anonymous_rpc, 'registro de recompensa é privado e a RPC exige autenticação');

    await asUser(bob);
    await denied(() => query('select * from public.quiz_xp_awards'), /permission denied/i, 'aluno não lê diretamente o registro de XP');
    await denied(() => submit(answers.slice(0, 9)), /todas as perguntas/i, 'respostas incompletas são recusadas no banco');
    await denied(() => submit([...answers.slice(0, 9), null]), /inválidas/i, 'resposta nula é recusada');
    await denied(() => submit([...answers.slice(0, 9), ' '.repeat(4)]), /inválidas/i, 'resposta vazia é recusada');
    await denied(() => submit([...answers.slice(0, 9), 'x'.repeat(301)]), /inválidas/i, 'resposta excessiva é recusada');
    await denied(() => submit(answers, 'Back-end', answers[2]), /corresponder/i, 'área e objetivo precisam corresponder às respostas');
    check(await xp(bob) === 0 && (await query('select * from public.quiz_answers')).length === 0, 'envio inválido não grava respostas nem XP');

    await submit(answers);
    const bobRows = await query('select question,answer from public.quiz_answers order by question');
    check(bobRows.length === 10 && bobRows.every((row, i) => row.question === i + 1 && row.answer === answers[i]), 'dez respostas são persistidas na ordem correta');
    check(await xp(bob) === 50, 'primeira conclusão concede 50 XP');
    const retake = answers.slice(); retake[1] = 'Back-end'; retake[4] = 'Ainda não sei';
    await submit(retake);
    check(await xp(bob) === 50 && (await query('select track from public.profiles where id=$1', [bob]))[0].track === 'Back-end', 'refazer atualiza a trilha sem duplicar XP');
    await query('update public.profiles set quiz_done=false where id=$1', [bob]);
    await submit(answers);
    check(await xp(bob) === 50, 'alterar a flag do perfil não permite receber XP novamente');
    check((await query('select * from public.quiz_answers where user_id=$1', [alice])).length === 0, 'RLS impede ler respostas de outro aluno');

    await asUser(alice);
    await submit(answers);
    check(await xp(alice) === 50 && (await query('select * from public.quiz_answers')).length === 10, 'aluna antiga pode fazer o diagnóstico sem ganhar XP repetido');

    await asUser(carol);
    await Promise.all([submit(answers.slice(0, 3)), submit(answers.slice(0, 3))]);
    check(await xp(carol) === 50 && (await query('select * from public.quiz_answers')).length === 3, 'cliente antigo e reenvios continuam funcionando sem XP duplicado');
    await pg.exec('reset role');
    await pg.exec(read('database/correcao-xp.sql'));
    await pg.exec(read('database/migracao-bloqueio-usuarios.sql'));
    const definition = (await query("select pg_get_functiondef('public.award_quiz_xp(jsonb,text,text)'::regprocedure) as body"))[0].body;
    check(definition.includes('quiz_xp_awards') && definition.includes('ensure_not_blocked'), 'reaplicar scripts históricos preserva a nova RPC');
    await asUser(carol); await submit(answers);
    check(await xp(carol) === 50, 'scripts históricos reaplicados não reabrem XP duplicado');
    await pg.exec(`reset role; update public.profiles set is_blocked=true where id='${bob}';`);
    await asUser(bob);
    await denied(() => submit(answers), /bloquead/i, 'usuário bloqueado não envia nivelamento');
    await pg.exec("reset role; select set_config('request.jwt.claim.sub', '', false); set role anon;");
    await denied(() => submit(answers), /permission denied/i, 'visitante anônimo não executa a RPC');
    await pg.exec('reset role');
    await pg.exec(schema.replace('create extension if not exists pgcrypto;', ''));
    await pg.exec(schema.replace('create extension if not exists pgcrypto;', ''));
    const final = await query('select count(*)::integer as n from public.quiz_xp_awards');
    check(final[0].n === 3, 'schema completo pode ser reaplicado sem apagar recompensas');
    console.log(`\n${checks} verificações do banco de nivelamento passaram.`);
  } finally {
    await pg.close();
  }
})().catch(error => { console.error(error.stack || error); process.exitCode = 1; });
